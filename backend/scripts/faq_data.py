"""Frequently asked questions of the «Синнамоны» cinnamon roll bakery, Russian + Tajik.

Rewritten 21.09.2026 from the bakery's own Instagram Direct archive (224 chats, 31.08–18.09.2026):
every answer here is what the owner actually replies to customers, not invented policy. The questions
are the ones that really recur — availability today, the pre-order rule, the address and whether there
is a café, the packing rule ("либо 4, либо 8"), prepayment, and "почему синнамоны, а не синнабоны".

Two kinds of answers still need the owner's eye before real customers see them:

* the shelf life, the allergy wording, the holiday and wholesale lead times — reasonable, but never
  stated in the archive, so check them in the admin panel («FAQ»);
* every Tajik text — written in the northern (Khujand) colloquial register the customers use
  ("доставка", "чандто", "мешавад?"), but a native speaker should still read it through.

The payment number is deliberately absent: it lives in «Настройки → Предоплата» and the bot sends it
itself, so these answers never go stale when it changes.

``keywords`` are the fallback when the model does not pick an entry: whole words/phrases compared
after normalization (lower case, ё→е, Tajik letters folded), so several word forms are listed. They
must not catch a plain price question: "сколько стоит коробка" is answered from the catalog, not here.

A keyword of two or more words is stronger: it adds its answer even next to the model's choice and
inside an order message (05 §5, "точная фраза владельца"). So such a phrase must name the question
itself ("сколько стоит доставка", "сможете сегодня") and never be something an order says on the way
("с доставкой", "с кремом", "можно заказать") — or every order would get that answer glued on.
They also carry the bot when the model is unavailable (the free quota ran out on 23–24.09.2026).
"""

